-- ---------------------------------------------------------------------------
-- 2.1  Tables
-- ---------------------------------------------------------------------------
IF OBJECT_ID('genbi.metric_catalog', 'U') IS NULL
CREATE TABLE genbi.metric_catalog (
    catalog_id             INT IDENTITY(1,1) PRIMARY KEY,
    view_name              SYSNAME        NOT NULL,       -- no schema, e.g. vw_sales
    column_name            SYSNAME        NOT NULL,
    business_name          NVARCHAR(100)  NOT NULL,
    column_role            NVARCHAR(12)   NOT NULL
        CONSTRAINT ck_column_role CHECK (column_role IN ('Measure','Dimension','Date','Identifier')),
    definition             NVARCHAR(600)  NOT NULL,
    calculation            NVARCHAR(300)  NULL,
    unit                   NVARCHAR(30)   NULL,
    is_additive            BIT            NULL,           -- 1 = can be summed, 0 = never sum, NULL = not a measure
    aggregation_rule       NVARCHAR(300)  NULL,
    contains_personal_data BIT            NOT NULL DEFAULT 0,
    status                 NVARCHAR(12)   NOT NULL DEFAULT 'Approved',
    owner                  NVARCHAR(100)  NULL,
    updated_at             DATETIME2      NOT NULL DEFAULT SYSDATETIME(),
    CONSTRAINT uq_metric_catalog UNIQUE (view_name, column_name)
);
GO

IF OBJECT_ID('genbi.metric_definition', 'U') IS NULL
CREATE TABLE genbi.metric_definition (
    metric_code          NVARCHAR(40)   NOT NULL PRIMARY KEY,
    metric_name          NVARCHAR(100)  NOT NULL,
    business_definition  NVARCHAR(500)  NOT NULL,
    preferred_view       SYSNAME        NOT NULL,
    sql_expression       NVARCHAR(600)  NOT NULL,
    time_rule            NVARCHAR(300)  NULL,
    caveat               NVARCHAR(500)  NULL,
    status               NVARCHAR(12)   NOT NULL DEFAULT 'Approved',
    owner                NVARCHAR(100)  NULL,
    updated_at           DATETIME2      NOT NULL DEFAULT SYSDATETIME()
);
GO

