-- ---------------------------------------------------------------------------
-- 2.4  One line per item, ready for the AI prompt (used in the Python phase)
-- ---------------------------------------------------------------------------
CREATE OR ALTER VIEW genbi.vw_prompt_metric_catalog
AS
SELECT 1 AS sec, view_name AS grp, CAST(catalog_id AS BIGINT) AS ord,
       CAST('semantic.' + view_name + '.' + column_name + ' [' + column_role + '] ' + definition
            + ISNULL(' | calc: ' + calculation, '')
            + CASE is_additive WHEN 1 THEN ' | additive' WHEN 0 THEN ' | NOT additive' ELSE '' END
            + ISNULL(' | rule: ' + aggregation_rule, '')
            + CASE WHEN contains_personal_data = 1 THEN ' | personal data' ELSE '' END
            AS NVARCHAR(MAX)) AS line_text
FROM genbi.metric_catalog
WHERE status = 'Approved'
UNION ALL
SELECT 2, 'Metric', ROW_NUMBER() OVER (ORDER BY metric_code),
       CAST('TRUSTED METRIC ' + metric_code + ' (' + metric_name + '): ' + business_definition
            + ' | use semantic.' + preferred_view
            + ' | expression: ' + sql_expression
            + ISNULL(' | time: ' + time_rule, '')
            + ISNULL(' | caveat: ' + caveat, '')
            AS NVARCHAR(MAX))
FROM genbi.metric_definition
WHERE status = 'Approved';
GO
