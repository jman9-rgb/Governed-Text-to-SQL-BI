/* =============================================================================
   08 SEMANTIC VIEWS
   The five business-friendly views the AI reads: vw_sales, vw_monthly_sales, vw_customer_metrics, vw_product_metrics, vw_data_range.
   vw_customer_metrics and vw_product_metrics read gold.report_customers and gold.report_products (step 07).
   ============================================================================= */
USE DataWarehouse;
GO

/*
===============================================================================
Semantic Layer
===============================================================================
Purpose:
    - Creates a business-friendly semantic layer on top of the Gold layer.
    - Provides curated views for Generative BI (GenBI), AI and analytical
      reporting.
    - Hides unnecessary warehouse complexity from AI and BI tools.
    - Provides predefined business metrics and consistent analytical grains.

Approved Semantic Views:
    1. semantic.vw_sales
    2. semantic.vw_monthly_sales
    3. semantic.vw_customer_metrics
    4. semantic.vw_product_metrics
    5. semantic.vw_data_range          (tells the AI what "latest", "last month" mean)

IMPORTANT:
    - AI/BI tools should query ONLY these semantic views.
    - Bronze and Silver layers should NOT be queried directly.
    - Prefer existing semantic metrics instead of recalculating them.
    - Always respect the grain of each semantic view.
    - Avoid unnecessary joins between semantic views.
    - Use DISTINCT counts where explicitly required.

===============================================================================
SEMANTIC VIEW SELECTION GUIDE
===============================================================================

Question Type                          Recommended View
-------------------------------------------------------------------------------
Transaction / order-line analysis      semantic.vw_sales
Monthly sales trends                   semantic.vw_monthly_sales
Customer performance / KPIs            semantic.vw_customer_metrics
Product performance / KPIs             semantic.vw_product_metrics
"Latest / last month / this year"      semantic.vw_data_range (reference dates)

===============================================================================
BUSINESS METRIC DEFINITIONS
===============================================================================

vw_sales
    quantity:        Number of units sold in the transaction.
    price:           Selling price associated with the sales transaction.
    sales_amount:    Revenue generated by the sales transaction.

vw_monthly_sales
    total_sales:           Total revenue generated during the month.
    total_orders:          Number of distinct orders during the month.
    total_quantity:        Total units sold during the month.
    purchasing_customers:  Number of distinct customers who made purchases during the month.

vw_customer_metrics
    total_orders:       Total number of orders placed by the customer.
    total_sales:        Total revenue generated by the customer.
    total_quantity:     Total number of units purchased by the customer.
    total_products:     Total number of distinct products purchased by the customer.
    avg_order_value:    Average revenue generated per order.
    avg_monthly_spend:  Average customer spending per month.
    recency:            Months between the customer's last order and the LAST ORDER DATE IN THE DATA.
    lifespan:           Months between the customer's first and last order.
    age / age_group:    Age at the last order date in the data; 'Unknown' when birthdate is missing.
    customer_segment:   VIP = lifespan >= 12 months and total_sales > 5000;
                        Regular = lifespan >= 12 months and total_sales <= 5000;
                        New = lifespan < 12 months.

vw_product_metrics
    total_orders:         Total number of orders containing the product.
    total_sales:          Total revenue generated by the product.
    total_quantity:       Total number of units sold.
    total_customers:      Total number of distinct customers who purchased the product.
    avg_selling_price:    Average selling price of the product.
    avg_order_revenue:    Average revenue generated per order for the product.
    avg_monthly_revenue:  Average monthly revenue generated by the product.
    recency_in_months:    Months between the product's last sale and the LAST ORDER DATE IN THE DATA.
    product_segment:      High-Performer = total_sales > 50000; Mid-Range = 10000 to 50000; Low-Performer = < 10000.

vw_data_range
    first_order_date, last_order_date, latest_month:
        Boundaries of the data. "Today", "this year", "last month" must be interpreted
        relative to last_order_date / latest_month, NOT the system clock.

===============================================================================
GENBI QUERY RULES
===============================================================================

1. Query only the approved semantic views.
2. Do not query Bronze or Silver tables directly.
3. Prefer predefined metrics from the semantic layer or Gold reporting
   layer instead of recreating the same metric.
4. Respect the grain of each view:
       - vw_sales              = transaction/order-line level
       - vw_monthly_sales      = monthly level
       - vw_customer_metrics   = customer level
       - vw_product_metrics    = product level
       - vw_data_range         = single row
5. Do NOT use COUNT(*) as an order count when using vw_sales.
   Use:  COUNT(DISTINCT order_number)
6. When calculating unique customers from vw_sales, use:
       COUNT(DISTINCT customer_key)
7. Use vw_monthly_sales for monthly sales trend questions whenever
   the required metric is already available.
8. Use vw_customer_metrics for customer-level KPI questions whenever
   the required metric is already available.
9. Use vw_product_metrics for product-level KPI questions whenever
   the required metric is already available.
10. Avoid unnecessary joins between semantic views.
11. Do not join views with different grains unless the business question
    requires it and the resulting aggregation is logically correct.
12. Avoid double-counting revenue, quantity, orders or customers.
13. Use SQL Server-compatible syntax.
14. Handle NULL values appropriately.
15. Avoid division by zero when calculating ratios (use NULLIF).
16. If a question is ambiguous, identify the ambiguity instead of making
    an unsupported assumption.
17. Relative dates ("last month", "this year", "recent") are relative to
    semantic.vw_data_range, never GETDATE().
18. Use DATEFROMPARTS instead of DATETRUNC (DATETRUNC needs SQL Server 2022+).
19. Cast to DECIMAL before dividing integers.

===============================================================================
*/

USE DataWarehouse;
GO

-- =============================================================================
-- 1. Create Semantic Schema (already created in section 1; kept so this part can be re-run alone)
-- =============================================================================
IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = 'semantic')
BEGIN
    EXEC('CREATE SCHEMA semantic');
END;
GO


-- =============================================================================
-- 2. Sales Semantic View
-- Grain: one row = one sales transaction / order line
-- Use for: transaction-level analysis, order details, customer-product analysis,
--          sales by customer / product / country, detailed investigations
-- Important: COUNT(DISTINCT order_number) for orders, COUNT(DISTINCT customer_key) for customers
-- =============================================================================
CREATE OR ALTER VIEW semantic.vw_sales
AS
SELECT
    -- Sales / Order Information
    f.order_number,
    f.order_date,
    f.shipping_date,
    f.due_date,

    -- Product Information
    f.product_key,
    p.product_number,
    p.product_name,
    p.category,
    p.subcategory,
    p.product_line,

    -- Customer Information
    f.customer_key,
    c.customer_number,
    CONCAT(c.first_name, ' ', c.last_name) AS customer_name,
    c.country,
    c.gender,
    c.marital_status,

    -- Sales Measures
    f.quantity,
    f.price,
    f.sales_amount

FROM gold.fact_sales AS f
LEFT JOIN gold.dim_products AS p
    ON f.product_key = p.product_key
LEFT JOIN gold.dim_customers AS c
    ON f.customer_key = c.customer_key;
GO


-- =============================================================================
-- 3. Monthly Sales Semantic View
-- Grain: one row = one calendar month
-- Use for: monthly revenue / order / quantity / customer-activity trends
-- =============================================================================
CREATE OR ALTER VIEW semantic.vw_monthly_sales
AS
SELECT
    DATEFROMPARTS(YEAR(order_date), MONTH(order_date), 1) AS sales_month,

    CAST(SUM(sales_amount) AS BIGINT) AS total_sales,
    COUNT(DISTINCT order_number)      AS total_orders,
    SUM(quantity)                     AS total_quantity,
    COUNT(DISTINCT customer_key)      AS purchasing_customers

FROM gold.fact_sales
WHERE order_date IS NOT NULL
GROUP BY DATEFROMPARTS(YEAR(order_date), MONTH(order_date), 1);
GO


-- =============================================================================
-- 4. Customer Metrics Semantic View
-- Source: gold.report_customers      Grain: one row = one customer
-- Use for: segmentation, ranking, customer value, purchasing behaviour, KPIs
-- =============================================================================
CREATE OR ALTER VIEW semantic.vw_customer_metrics
AS
SELECT
    -- Customer Identification
    customer_key,
    customer_number,
    customer_name,

    -- Customer Attributes
    age,
    age_group,
    customer_segment,

    -- Customer Activity
    last_order_date,
    recency,
    lifespan,

    -- Customer KPIs
    total_orders,
    total_sales,
    total_quantity,
    total_products,
    avg_order_value,
    avg_monthly_spend

FROM gold.report_customers;
GO


-- =============================================================================
-- 5. Product Metrics Semantic View
-- Source: gold.report_products       Grain: one row = one product
-- Use for: product performance, ranking, segmentation, revenue, demand
-- =============================================================================
CREATE OR ALTER VIEW semantic.vw_product_metrics
AS
SELECT
    -- Product Identification
    product_key,
    product_name,

    -- Product Classification
    category,
    subcategory,

    -- Product Information
    cost,
    last_sale_date,
    recency_in_months,
    lifespan,
    product_segment,

    -- Product KPIs
    total_orders,
    total_sales,
    total_quantity,
    total_customers,
    avg_selling_price,
    avg_order_revenue,
    avg_monthly_revenue

FROM gold.report_products;
GO


-- =============================================================================
-- 6. Data Range Semantic View
-- Grain: single row.
-- Use for: telling the AI what the data's "now" is.
-- =============================================================================
CREATE OR ALTER VIEW semantic.vw_data_range
AS
SELECT
    MIN(order_date) AS first_order_date,
    MAX(order_date) AS last_order_date,
    DATEFROMPARTS(YEAR(MAX(order_date)), MONTH(MAX(order_date)), 1) AS latest_month
FROM gold.fact_sales
WHERE order_date IS NOT NULL;
GO


/* ---------- Refresh the metadata of the semantic views (two passes: some views read other views) ---------- */
DECLARE @pass INT = 1, @v NVARCHAR(300);
WHILE @pass <= 2
BEGIN
    DECLARE cur_v CURSOR LOCAL FAST_FORWARD FOR
        SELECT QUOTENAME(SCHEMA_NAME(schema_id)) + N'.' + QUOTENAME(name)
        FROM sys.views WHERE schema_id = SCHEMA_ID('semantic');
    OPEN cur_v; FETCH NEXT FROM cur_v INTO @v;
    WHILE @@FETCH_STATUS = 0
    BEGIN
        EXEC sys.sp_refreshview @v;
        FETCH NEXT FROM cur_v INTO @v;
    END
    CLOSE cur_v; DEALLOCATE cur_v;
    SET @pass += 1;
END
GO
